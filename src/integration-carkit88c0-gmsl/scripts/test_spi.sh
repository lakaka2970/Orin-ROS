#!/bin/bash
# gmsl_reg_read.sh - GMSL 调试寄存器批量读取脚本
# 用法：./gmsl_reg_read.sh [总线号]  默认总线号为2

I2C_BUS=${1:-2}   # 若未指定参数，默认使用 I2C 总线 2

# 读取一个寄存器并打印
read_reg() {
    local dev=$1
    local addr_hi=$2
    local addr_lo=$3
    local desc="$4"
    local val
    val=$(i2ctransfer -y -f "$I2C_BUS" w2@"$dev" "$addr_hi" "$addr_lo" r1 2>/dev/null)
    if [ $? -eq 0 ] && [ -n "$val" ]; then
        printf "  0x%02X 0x%02X%02X  %-30s = 0x%02X\n" "$dev" "$addr_hi" "$addr_lo" "$desc" "0x$val"
    else
        printf "  0x%02X 0x%02X%02X  %-30s = 读取失败\n" "$dev" "$addr_hi" "$addr_lo" "$desc"
    fi
}

# 打印分隔线
print_header() {
    echo "============================================================"
    echo "$1"
    echo "------------------------------------------------------------"
}

